export const CABINET_WIDTH = Math.max(
  ...CABINET_FRAMES.flat().map(line => line.length)
)
export const CABINET_HEIGHT = CABINET_FRAMES[0]!.length
export const CABINET_FRAMES_COUNT = CABINET_FRAMES.length

/**
 * One frame of the cabinet.
 *
 * `frame` counts landed reels: 0 is every reel spinning, and
 * CABINET_FRAMES_COUNT - 1 is QUBIT fully landed. Frames are pre-rendered, so
 * a tick costs a lookup and never a re-layout.
 */
export const slotCabinet = (c: ThemeColors, frame: number): Line[] => {
  const at = Math.min(Math.max(0, Math.trunc(frame)), CABINET_FRAMES.length - 1)

  return CABINET_FRAMES[at]!.map(row => cabinetLine(row, c))
}

/**
 * Colour a cabinet row.
 *
 * A row still carrying a spinning reel recedes to the border tone; the landed
 * rows take the primary tone so the eye follows the word arriving. The
 * payline arrows keep the accent tone either way — they mark the line every
 * reel stops on, so they must stay visible above both states.
 */
const cabinetLine = (row: string, c: ThemeColors): Line => {
  if (row.includes('►') || row.includes('◄')) {
    return [c.accent, row]
  }

  return [row.includes(CABINET_SPIN) ? c.border : c.primary, row]
}

